// Generates THIRD_PARTY_NOTICES.md from the real license files of everything we bundle.
// Run: pnpm notices   (re-run after changing dependencies or the foliate-js submodule)

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const read = (p) => readFileSync(join(root, p), "utf8").trim();
const version = (pkg) => JSON.parse(read(`node_modules/${pkg}/package.json`)).version;

const entries = [
  { name: "foliate-js", license: "MIT", url: "https://github.com/johnfactotum/foliate-js", file: "vendor/foliate-js/LICENSE", note: "Book parsing and rendering engine, vendored as a git submodule." },
  { name: "zip.js", license: "BSD-3-Clause", url: "https://github.com/gildas-lormeau/zip.js", file: "licenses/zip.js.LICENSE.txt", note: "Bundled inside foliate-js." },
  { name: "fflate", license: "MIT", url: "https://github.com/101arrowz/fflate", file: "licenses/fflate.LICENSE.txt", note: "Bundled inside foliate-js." },
  { name: "PDF.js", license: "Apache-2.0", url: "https://github.com/mozilla/pdf.js", file: "licenses/pdf.js.LICENSE.txt", note: "Bundled inside foliate-js (PDF support is not enabled in this app)." },
  { name: "React", license: "MIT", url: "https://github.com/facebook/react", file: "node_modules/react/LICENSE", ver: () => version("react") },
  { name: "React DOM", license: "MIT", url: "https://github.com/facebook/react", file: "node_modules/react-dom/LICENSE", ver: () => version("react-dom") },
  { name: "zustand", license: "MIT", url: "https://github.com/pmndrs/zustand", file: "node_modules/zustand/LICENSE", ver: () => version("zustand") },
  { name: "Tauri JavaScript API", license: "Apache-2.0 OR MIT", url: "https://github.com/tauri-apps/tauri", file: "node_modules/@tauri-apps/api/LICENSE-APACHE-2.0", ver: () => version("@tauri-apps/api") },
  ...[
    ["Inter", "inter"],
    ["Manrope", "manrope"],
    ["Fraunces", "fraunces"],
    ["Newsreader", "newsreader"],
    ["Literata", "literata"],
    ["Source Serif 4", "source-serif-4"],
  ].map(([name, id]) => ({
    name: `${name} (font)`,
    license: "SIL Open Font License 1.1",
    url: `https://fontsource.org/fonts/${id}`,
    file: `node_modules/@fontsource-variable/${id}/LICENSE`,
    ver: () => version(`@fontsource-variable/${id}`),
    note: "Distributed via Fontsource.",
  })),
];

const out = [
  "# Third-party notices",
  "",
  "CoolReader (Folio) is licensed under the Apache License 2.0 (see `LICENSE`). It includes the following third-party software and fonts, each under its own license, reproduced below.",
  "",
  "The desktop shell is built with [Tauri](https://tauri.app) and its Rust crates (Apache-2.0 / MIT and similar permissive licenses). Their full list and license terms are in `src-tauri/Cargo.lock` and can be produced with a tool such as `cargo about`.",
  "",
  "This file is generated by `scripts/gen-notices.mjs`. Do not edit it by hand.",
  "",
];

for (const e of entries) {
  if (!existsSync(join(root, e.file))) throw new Error(`Missing license file for ${e.name}: ${e.file}`);
  const v = e.ver ? ` ${e.ver()}` : "";
  out.push("---", "", `## ${e.name}${v}`, "", `- License: ${e.license}`, `- Source: ${e.url}`);
  if (e.note) out.push(`- ${e.note}`);
  out.push("", "```text", read(e.file), "```", "");
}

writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), out.join("\n"));
console.log(`Wrote THIRD_PARTY_NOTICES.md (${entries.length} components)`);
